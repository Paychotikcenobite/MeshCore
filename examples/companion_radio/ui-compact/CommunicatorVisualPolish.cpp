void CommunicatorAppScreen::redrawHeaderActionIconsFluent(DisplayDriver& d) {
  const ColorVal bg = _light_mode ? (ColorVal)0xF7DF : (ColorVal)0x0084;
  const ColorVal card = _light_mode ? (ColorVal)0xFFFF : (ColorVal)0x08E6;
  const ColorVal divider = _light_mode ? (ColorVal)0xDED7 : (ColorVal)0x29CF;
  const ColorVal text = _light_mode ? (ColorVal)0x14E5 : (ColorVal)0xFFFF;
  const ColorVal radioOk = _light_mode ? (ColorVal)0x246B : (ColorVal)0x25CB;
  const ColorVal shadow = darken565(bg, 110);
  const ColorVal highlight = lighten565(card, _light_mode ? 24 : 18);

  // Soft one-pixel shadow + bright top edge gives the header controls depth
  // without turning the compact UI into skeuomorphism.
  d.setColor(shadow); d.fillRoundRect(238,5,36,33,7); d.fillRoundRect(279,5,36,33,7);
  d.setColor(card); d.fillRoundRect(238,3,36,33,7); d.fillRoundRect(279,3,36,33,7);
  d.setColor(divider); d.drawRoundRect(238,3,36,33,7); d.drawRoundRect(279,3,36,33,7);
  d.setColor(highlight); d.drawLine(246,4,266,4); d.drawLine(287,4,307,4);

  drawAlphaMask4(d,244,7,WIFI24_A4,24,24,text,card);
  drawAlphaMask4(d,285,7,SETTINGS24_A4,24,24,text,card);

  // Keep radio health separate from the glyph itself. This lets the icon stay
  // visually Windows-like instead of coloring the entire Wi-Fi fan green.
  d.setColor(radioOk); d.fillCircle(269,31,2);
  d.setColor(text);
}
