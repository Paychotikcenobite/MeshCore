ColorVal blend565(ColorVal fg, ColorVal bg, uint8_t a4) {
  if (a4 == 0) return bg;
  if (a4 >= 15) return fg;
  uint16_t fr=(fg>>11)&31, fg6=(fg>>5)&63, fb=fg&31;
  uint16_t br=(bg>>11)&31, bg6=(bg>>5)&63, bb=bg&31;
  uint16_t r=(fr*a4+br*(15-a4)+7)/15;
  uint16_t g=(fg6*a4+bg6*(15-a4)+7)/15;
  uint16_t b=(fb*a4+bb*(15-a4)+7)/15;
  return (ColorVal)((r<<11)|(g<<5)|b);
}

ColorVal darken565(ColorVal c, uint8_t amount) {
  uint16_t r=(c>>11)&31, g=(c>>5)&63, b=c&31;
  r=(r*(255-amount))/255; g=(g*(255-amount))/255; b=(b*(255-amount))/255;
  return (ColorVal)((r<<11)|(g<<5)|b);
}

ColorVal lighten565(ColorVal c, uint8_t amount) {
  uint16_t r=(c>>11)&31, g=(c>>5)&63, b=c&31;
  r += ((31-r)*amount)/255; g += ((63-g)*amount)/255; b += ((31-b)*amount)/255;
  return (ColorVal)((r<<11)|(g<<5)|b);
}

uint8_t alphaAt(const uint8_t* mask, int pixel) {
  uint8_t v = mask[pixel >> 1];
  return (pixel & 1) ? (v & 0x0F) : (v >> 4);
}

void drawAlphaMask4(DisplayDriver& d, int x, int y, const uint8_t* mask,
                    int w, int h, ColorVal fg, ColorVal bg) {
  for (int yy=0; yy<h; ++yy) {
    int xx=0;
    while (xx<w) {
      uint8_t a=alphaAt(mask, yy*w+xx);
      if (!a) { ++xx; continue; }
      if (a==15) {
        int start=xx;
        while (xx<w && alphaAt(mask, yy*w+xx)==15) ++xx;
        d.setColor(fg); d.fillRect(x+start,y+yy,xx-start,1);
        continue;
      }
      d.setColor(blend565(fg,bg,a)); d.fillRect(x+xx,y+yy,1,1);
      ++xx;
    }
  }
}

